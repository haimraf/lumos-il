export type ContactTopicId = (typeof CONTACT_TOPICS)[number]["id"];

const FALLBACK_TOPIC = CONTACT_TOPICS[CONTACT_TOPICS.length - 1];

const CONTACT_TOPIC_LOOKUP = new Map<ContactTopicId, ContactTopic>(
  CONTACT_TOPICS.map((topic) => [topic.id, topic]),
);

export function normalizeContactTopic(value: string | null | undefined): ContactTopicId {
  if (!value) return FALLBACK_TOPIC.id;

  const normalized = value.trim().toLowerCase() as ContactTopicId;
  return CONTACT_TOPIC_LOOKUP.has(normalized) ? normalized : FALLBACK_TOPIC.id;
}

export function getContactTopicConfig(value: string | null | undefined) {
  return CONTACT_TOPIC_LOOKUP.get(normalizeContactTopic(value)) || FALLBACK_TOPIC;
}

export function getContactTopicLabel(value: string | null | undefined) {
  return getContactTopicConfig(value).label;
}