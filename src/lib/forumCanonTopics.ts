/** מחזיר נושא לפי סבב קבוע, כך שכל נושא חוזר רק אחרי שכולם עברו. */
export function pickCanonTopic(rotationIndex: number): CanonTopic {
  const safeIndex = Math.abs(Math.trunc(rotationIndex)) % CANON_TOPICS.length;
  return CANON_TOPICS[safeIndex];
}
